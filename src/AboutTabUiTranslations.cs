        if (lang.Equals(LocalizationService.Indonesian, StringComparison.OrdinalIgnoreCase)) return EnToId;
        if (lang.Equals(LocalizationService.Portuguese, StringComparison.OrdinalIgnoreCase) || lang.Equals(LocalizationService.Brazil, StringComparison.OrdinalIgnoreCase)) return EnToPt;
        if (lang.Equals(LocalizationService.Malay, StringComparison.OrdinalIgnoreCase)) return EnToMs;
        if (lang.Equals(LocalizationService.Japanese, StringComparison.OrdinalIgnoreCase)) return EnToJa;
        if (lang.Equals(LocalizationService.Chinese, StringComparison.OrdinalIgnoreCase)) return EnToZh;
        if (lang.Equals(LocalizationService.Thai, StringComparison.OrdinalIgnoreCase)) return EnToTh;
        if (lang.Equals(LocalizationService.Khmer, StringComparison.OrdinalIgnoreCase)) return EnToKm;
        if (lang.Equals(LocalizationService.Lao, StringComparison.OrdinalIgnoreCase)) return EnToLo;
        if (lang.Equals(LocalizationService.Korean, StringComparison.OrdinalIgnoreCase)) return EnToKo;
        if (lang.Equals(LocalizationService.Russian, StringComparison.OrdinalIgnoreCase)) return EnToRu;
        if (lang.Equals(LocalizationService.Ukrainian, StringComparison.OrdinalIgnoreCase)) return EnToUk;
        if (lang.Equals(LocalizationService.SpanishLatin, StringComparison.OrdinalIgnoreCase)
            || lang.Equals(LocalizationService.SpanishArgentina, StringComparison.OrdinalIgnoreCase)
