    private static Dictionary<string, string> D(params (string en, string tr)[] rows)
    {
        var d = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var (en, tr) in rows)
            d[en] = tr;
        return d;
    }

